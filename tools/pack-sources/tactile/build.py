#!/usr/bin/env python3
"""Builds packs/tactile from the files fetch.sh downloaded.

    tools/pack-sources/tactile/fetch.sh DOWNLOADS
    python3 tools/pack-sources/tactile/build.py --downloads DOWNLOADS [--out packs/tactile]

Every input is CC0-1.0 (checked on each Freesound page on 2026-10-02, see SOURCES.md).
The script checks each download against the size and git blob SHA-1 that GitHub reported for
clatterbox commit 9dca88f, so a changed upstream file stops the build.

Each recording is a whole tap: the key-down, then the key-up 90-170 ms later in the same take.
The build splits every take at the quietest point between the two strokes, so the key-down
plays on press and the take's own key-up on release (and a press never carries a key-up).

The StavSounds takes were recorded about 20 dB apart in loudness. Each take gets its own
levelling gain, which brings its key-down to within LEVEL_BAND_DB of the median take's
K-weighted loudness and keeps its key-up from going above that band (a take already inside
it is left as recorded); the gain applies to the whole take, so every take keeps its own
key-down/key-up balance. Two takes (DROPPED) are left out; SOURCES.md says why.
"""

