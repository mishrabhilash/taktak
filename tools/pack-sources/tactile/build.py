def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--downloads", type=Path, required=True,
                    help="the folder given to fetch.sh")
    ap.add_argument("--out", type=Path, default=REPO_ROOT / "packs" / PACK_ID)
    ap.add_argument("--force", action="store_true",
                    help="replace an output folder that this script did not create")
    ap.add_argument("--skip-verify", action="store_true",
                    help="testing only: do not check sizes and SHA-1s (SOURCES.md says so)")
    args = ap.parse_args()

    src_dir = args.downloads / "clatterbox-tactile"
    if not args.skip_verify:
        problems = [p for s in SOURCES for p in pl.verify_download(src_dir / s.file, s.size, s.blob)]
        problems += [p for f, size, blob in PROVENANCE_DOCS
                     for p in pl.verify_download(src_dir / f, size, blob)]
        if problems:
            print("download check failed:\n  " + "\n  ".join(problems), file=sys.stderr)
            return 1

    out = args.out
    if out.exists():
        sources_md = out / "SOURCES.md"
        ours = sources_md.is_file() and MARKER in sources_md.read_text(encoding="utf-8")
        if not ours and not args.force:
            print(f"{out} exists and was not made by this script; use --force", file=sys.stderr)
            return 1
        shutil.rmtree(out)

    # Decode and high-pass every recording at its own sample rate, then split each tap into
    # its key-down (press) and key-up (release).
    infos: dict[str, dict] = {}
    rates: dict[str, int] = {}
    splits: dict[str, pl.TapSplit] = {}
    floors: dict[str, float] = {}  # each take's noise floor, used to cut both its strokes
    parts: dict[tuple[str, str], np.ndarray] = {}
    for s in SOURCES:
        path = src_dir / s.file
        infos[s.file] = pl.probe(path)
        rates[s.file] = infos[s.file]["rate"]
        x = pl.highpass(pl.decode_mono(path, rates[s.file]), rates[s.file])
        sp = pl.split_tap(x, rates[s.file])
        if sp is None:
            raise SystemExit(f"{s.file}: no separate key-up found; check the recording")
        splits[s.file] = sp
        floors[s.file] = pl.noise_floor(x, rates[s.file])
        parts[s.file, "press"] = x[:sp.split]
        # From one pre-roll before release_from, so the key-up fades in from zero there.
        parts[s.file, "release"] = x[sp.release_from - pre_roll(rates[s.file]):]

    unknown = set(DROPPED) - {s.file for s in SOURCES if s.role == "key"}
    if unknown:
        raise SystemExit(f"DROPPED names files that are not StavSounds takes: {sorted(unknown)}")
    used = [s for s in SOURCES if s.file not in DROPPED]
    keys = [s for s in used if s.role == "key"]

    # Loudness of every StavSounds stroke as recorded, measured as synth-packs does (first
    # 100 ms, K-weighted) on the stroke as it would be cut at unity gain.
    takes = [s for s in SOURCES if s.role == "key"]
    recorded_lk: dict[tuple[str, str], float] = {}
    for s in takes:
        rate = rates[s.file]
        recorded_lk[s.file, "press"] = pl.k_loudness(
            pl.cut(parts[s.file, "press"], rate, MAX_SECONDS, 1.0, floor=floors[s.file])[0], rate)
        recorded_lk[s.file, "release"] = pl.k_loudness(
            pl.cut(parts[s.file, "release"], rate, MAX_SECONDS, 1.0, min_onset=pre_roll(rate),
                   floor=floors[s.file])[0], rate)

    # Levelling: one gain per kept take, the smallest that puts its key-down within
    # LEVEL_BAND_DB of the median take's and its key-up no louder than the band's top.
    median_lk = float(np.median([recorded_lk[s.file, "press"] for s in keys]))
    level: dict[str, float] = {}
    for s in keys:
        gain_db = level_gain_db(recorded_lk[s.file, "press"], recorded_lk[s.file, "release"],
                                median_lk, LEVEL_BAND_DB)
        if gain_db is None:
            up_over_down = recorded_lk[s.file, "release"] - recorded_lk[s.file, "press"]
            raise SystemExit(f"{s.file}: its key-up is {up_over_down:.1f} dB louder than its "
                             "key-down, more than the levelling band allows; check the split, "
                             "or list the take in DROPPED")
        level[s.file] = pl.undb(gain_db)

    # One gain per source on top of that. StavSounds: levelled key-down median peak to
    # -6 dBFS, capped so that no StavSounds file peaks above the ceiling. Enter and backspace:
    # their key-down at the role offset from where that median lands.
    peaks = {k: pl.peak(x) for k, x in parts.items()}
    press_median = float(np.median([peaks[s.file, "press"] * level[s.file] for s in keys]))
    key_gain = pl.undb(PRESS_MEDIAN_PEAK) / press_median
    ceiling = pl.undb(pl.CEILING_DBFS)
    loudest = max(peaks[s.file, a] * level[s.file] for s in keys for a in ACTIONS) * key_gain
    if loudest > ceiling:
        key_gain *= ceiling / loudest
    gains: dict[str, float] = {}
    for s in used:
        if s.role == "key":
            gains[s.file] = key_gain * level[s.file]
        else:
            target = press_median * key_gain * pl.undb(ROLE_OFFSET_DB[s.role])
            gains[s.file] = target / peaks[s.file, "press"]

    # Headroom: one trim for every file, so the balance between them is unchanged.
    trim = pl.headroom_trim([parts[s.file, a] * gains[s.file] for s in used for a in ACTIONS],
                            VARIATION["volume"])
    gains = {f: g * trim for f, g in gains.items()}
    press_median_out = press_median * key_gain * trim

    # Trim each stroke: the onset is where it will reach the loader's silence threshold.
    # Cut positions are kept relative to the decoded source (the key-up starts at the split).
    cuts: dict[tuple[str, str], tuple[np.ndarray, pl.Cut]] = {}
    for s in used:
        rate = rates[s.file]
        for a in ACTIONS:
            if a == "press":
                y, c = pl.cut(parts[s.file, a], rate, MAX_SECONDS, gains[s.file],
                              floor=floors[s.file])
            else:
                pre = pre_roll(rate)
                y, c = pl.cut(parts[s.file, a], rate, MAX_SECONDS, gains[s.file], min_onset=pre,
                              floor=floors[s.file])
                shift = splits[s.file].release_from - pre
                c = dataclasses.replace(c, start=c.start + shift, onset=c.onset + shift,
                                        end=c.end + shift)
            cuts[s.file, a] = (y, c)

    out.mkdir(parents=True)
    rendered: dict[str, np.ndarray] = {}
    for s in used:
        for a in ACTIONS:
            name = s.out(a)
            pl.write_wav(out / name, cuts[s.file, a][0] * gains[s.file], rates[s.file])
            # The preview is mixed at RATE: a file at another rate is resampled for it by ffmpeg.
            if rates[s.file] == RATE:
                rendered[name] = pl.read_wav16(out / name)[0]
            else:
                rendered[name] = pl.decode_mono(out / name, RATE)
    true_peaks = {s.out(a): pl.true_peak(pl.read_wav16(out / s.out(a))[0])
                  for s in used for a in ACTIONS}
    headroom = max(true_peaks.values()) * (1.0 + VARIATION["volume"])
    if headroom > pl.undb(pl.MAX_TRUE_PEAK_DBFS + 0.05):
        raise SystemExit(f"loudest file reaches {pl.db(headroom):.2f} dBFS with the volume "
                         "variation; the headroom trim did not hold")

    # The shipped strokes, measured as synth-packs measures them: the levelling must hold, so
    # that a few loud takes cannot carry a pack whose typical keystroke is much quieter.
    shipped_lk = {(s.file, a): pl.k_loudness(*pl.read_wav16(out / s.out(a)))
                  for s in keys for a in ACTIONS}
    shared_db = pl.db(key_gain * trim)
    band = (median_lk - LEVEL_BAND_DB + shared_db, median_lk + LEVEL_BAND_DB + shared_db)
    for (file, a), lk in shipped_lk.items():
        if lk > band[1] + BAND_SLACK_DB or (a == "press" and lk < band[0] - BAND_SLACK_DB):
            raise SystemExit(f"{file} {stroke_name(a)} ships at {lk:.1f} LK, outside the "
                             f"levelling band {band[0]:.1f}..{band[1]:.1f} LK")
    shipped_downs = [shipped_lk[s.file, "press"] for s in keys]

    groups: dict[str, dict[str, list[str]]] = {
        "alphanumeric": {a: [s.out(a) for s in keys] for a in ACTIONS},
    }
    for role in ("enter", "backspace"):
        groups[role] = {a: [s.out(a) for s in used if s.role == role] for a in ACTIONS}

    manifest = build_manifest(groups, len(keys))
    (out / "pack.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
                                   encoding="utf-8")

    preview_sounds = {f"{token}.{a}": [rendered[f] for f in groups[group][a]]
                      for token, group in (("k", "alphanumeric"), ("enter", "enter"))
                      for a in ACTIONS}
    script = ["k"] * 4 + ["space"] + ["k"] * 3 + ["space"] + ["k"] * 3 + ["enter"]
    preview = pl.render_preview(RATE, script, preview_sounds, seed=0x7AC711E,
                                volume_variation=manifest["variation"]["volume"])
    pl.write_wav(out / "preview.wav", preview, RATE)

    sets = {f"{g}.{a}": files for g, ga in groups.items() for a, files in ga.items()}
    table = pl.stats_table(out, sets)
    write_sources_md(out, src_dir, splits, cuts, infos, gains, trim, press_median_out,
                     true_peaks, table, args.skip_verify,
                     Levelling(recorded_lk, median_lk, level, shipped_lk))
    print(table)
    print(f"\nkey-downs as shipped: {max(shipped_downs) - min(shipped_downs):.1f} dB spread, "
          f"median {float(np.median(shipped_downs)):.2f} LK, power average "
          f"{pl.power_mean_db(shipped_downs):.2f} LK (at volume 1.0)")
    total = sum(p.stat().st_size for p in out.rglob("*") if p.is_file())
    print(f"\nwrote {out} ({total} bytes)")
    return 0


def pre_roll(rate: int) -> int:
    return round(pl.PRE_ROLL_S * rate)


def stroke_name(action: str) -> str:
    return {"press": "key-down", "release": "key-up"}[action]


def level_gain_db(down_lk: float, up_lk: float, median_lk: float, band_db: float) -> float | None:
    """A take's levelling gain in dB: the smallest that puts its key-down within band_db of
    median_lk and its key-up no louder than median_lk + band_db (0 when it already is), or
    None when no gain can, because the key-up is more than 2 * band_db above the key-down."""
    lowest = median_lk - band_db - down_lk
    highest = min(median_lk + band_db - down_lk, median_lk + band_db - up_lk)
    if lowest > highest:
        return None
    return min(max(0.0, lowest), highest)


@dataclass(frozen=True)
class Levelling:
    """The per-take levelling, for SOURCES.md."""

    recorded_lk: dict  # (file, action) -> LK of the stroke as recorded (unity gain)
    median_lk: float  # median recorded key-down LK of the kept takes
    level: dict  # file -> levelling gain (linear) of each kept take
    shipped_lk: dict  # (file, action) -> LK of the stroke as shipped (volume 1.0)


