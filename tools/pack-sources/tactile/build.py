# Level of each source in the pack. First each StavSounds take is levelled with one gain for
# the take, the smallest (none for a take already inside the band) that puts its key-down's
# K-weighted loudness (pl.k_loudness) within LEVEL_BAND_DB of the median take's key-down and
# its key-up no louder than the top of that band; each take keeps its key-down/key-up
# balance. A take whose key-up is more than twice the band louder than its key-down cannot
# be levelled, and the build stops on it (it would sound like a late keystroke: the click
# comes when the key is let go). Then the levelled key-downs set the pack gain (it aims
# their median peak at -6 dBFS, capped so that no StavSounds file, key-down or key-up, peaks
# above the ceiling); the Enter and backspace recordings each get one gain that puts their
# key-down peak this many dB from the StavSounds key-downs' median peak as it ends up.
LEVEL_BAND_DB = 3.0
PRESS_MEDIAN_PEAK = pl.TARGET_MEDIAN_PEAK_DBFS
ROLE_OFFSET_DB = {"enter": 1.0, "backspace": 0.0}
MAX_SECONDS = 0.4
# The shipped strokes are measured again and must keep to the band within this much (the
# levelling is measured before the final gains and 16-bit rounding), or the build stops.
BAND_SLACK_DB = 0.5
# StavSounds takes that are decoded and measured but not used, with the reason (SOURCES.md
# adds the measurements). Their files are still numbered after their clatterbox download, so
# press-NN.wav and release-NN.wav always come from down-NN.mp3.
DROPPED = {
    "down-02.mp3": "a soft key-down that never bottomed out, then a hard top-out, so the "
                   "keystroke's click would come late, when the key is let go",
    "down-12.mp3": "the quietest key-down by far, with a key-up louder than it: it would need "
                   "by far the largest levelling boost, and its click would still come late, on "
                   "the key-up",
}
# Playback level, written to pack.json as "volume"; it changes no audio file. Measured on the
# built pack with
#     cargo run -p synth-packs --release -- loudness packs/tactile
# (tools/synth-packs/src/loudness.rs): typing reads LK_AS_BUILT at volume 1.0, and VOLUME puts
# it within the 0.5 dB tolerance of the reference (pl.REFERENCE_LK). VOLUME_FOR_REFERENCE is the
# volume the reference would take when headroom caps VOLUME below it, None otherwise. Recorded
# in SOURCES.md; re-measure whenever the processing here changes.
VOLUME = 0.98
LK_AS_BUILT = -26.07
VOLUME_FOR_REFERENCE: float | None = None


@dataclass(frozen=True)
class Source:
    file: str  # file name in clatterbox's pack (and in the download folder)
    size: int
    blob: str  # git blob SHA-1 at CLATTERBOX_COMMIT
    fs_id: int
    author: str
    title: str
    original: str  # the Freesound original, as its page describes it
    role: str  # key | enter | backspace
    stem: str  # output name stem: sounds/<stem>-press.wav or sounds/<stem>-release.wav,
    # or, for the StavSounds keys, sounds/press-NN.wav and sounds/release-NN.wav

    @property
    def page(self) -> str:
        return f"https://freesound.org/people/{self.author}/sounds/{self.fs_id}/"

    def out(self, action: str) -> str:
        if self.role == "key":
            return f"sounds/{action}-{self.stem}.wav"
        return f"sounds/{self.stem}-{action}.wav"


def _stav(n: int, file: str, size: int, blob: str, fs_id: int, title: str, original: str) -> Source:
    return Source(file, size, blob, fs_id, "StavSounds", title, original, "key", f"{n:02d}")


