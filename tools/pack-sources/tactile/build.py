def offset_text(offset_db: float) -> str:
    """Where a role's key-down peak sits relative to the key-downs' median peak, in words."""
    if abs(offset_db) < 0.05:
        return "level with that median"
    return f"{abs(offset_db):.0f} dB {'above' if offset_db > 0 else 'below'} that median"


def spread_lk(lev: Levelling, keys: list[Source]) -> float:
    """dB between the loudest and the quietest of these takes' key-downs, as recorded."""
    values = [lev.recorded_lk[s.file, "press"] for s in keys]
    return max(values) - min(values)


def spread_db(cuts: dict, action: str, lev: Levelling) -> float:
    """dB of peak level between the loudest and the quietest used StavSounds stroke of one
    kind, after levelling."""
    peaks = [pl.peak(cuts[s.file, action][0]) * lev.level[s.file]
             for s in SOURCES if s.role == "key" and s.file not in DROPPED]
    return pl.db(max(peaks)) - pl.db(min(peaks))


